"""Writes project.godot, icon.svg and .gitignore for the generated project."""
from __future__ import annotations

import logging
import re
import string
import subprocess
from typing import Any

from core.config import GodotConfig
from core.safe_files import resolve_inside
from core.schemas import ProjectContext

logger = logging.getLogger(__name__)

# Godot 4 `Key` enum values used for `physical_keycode`.
# Verify once in the editor (Project > Project Settings > Input Map). If one is wrong, fix it here only.
KEYCODES: dict[str, int] = {
    "Space": 32,
    "Escape": 4194305,
    "Enter": 4194309,
    "Left": 4194319,
    "Up": 4194320,
    "Right": 4194321,
    "Down": 4194322,
    "Shift": 4194325,
    "Ctrl": 4194326,
}
KEYCODES.update({letter: ord(letter) for letter in string.ascii_uppercase})

_VERSION_RE = re.compile(r"(\d+)\.(\d+)")


class ProjectWriteError(RuntimeError):
    """Raised when project.godot cannot reference what the programmer produced."""


def _esc(text: str) -> str:
    """Escape a value for a double-quoted project.godot string."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("\r", " ")


def _color(hex_value: str) -> str:
    r, g, b = (int(hex_value[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return f"Color({r:.4f}, {g:.4f}, {b:.4f}, 1)"


def _key_event(code: int) -> str:
    return (
        'Object(InputEventKey,"resource_local_to_scene":false,"resource_name":"","device":-1,'
        '"window_id":0,"alt_pressed":false,"shift_pressed":false,"ctrl_pressed":false,'
        f'"meta_pressed":false,"pressed":false,"keycode":0,"physical_keycode":{code},'
        '"key_label":0,"unicode":0,"echo":false,"script":null)'
    )


def _mouse_event() -> str:
    return (
        'Object(InputEventMouseButton,"resource_local_to_scene":false,"resource_name":"",'
        '"device":-1,"window_id":0,"alt_pressed":false,"shift_pressed":false,"ctrl_pressed":false,'
        '"meta_pressed":false,"button_mask":1,"position":Vector2(0, 0),'
        '"global_position":Vector2(0, 0),"factor":1.0,"button_index":1,"pressed":true,'
        '"double_click":false,"script":null)'
    )


def _event_for(key: str) -> str:
    if key == "MouseLeft":
        return _mouse_event()
    if key not in KEYCODES:
        raise ProjectWriteError(f"unsupported key '{key}'")
    return _key_event(KEYCODES[key])


def detect_godot_version(godot: GodotConfig) -> str | None:
    """Return 'major.minor' from config, else from `godot --version`, else None."""
    if godot.target_version:
        match = _VERSION_RE.search(godot.target_version[:40])
        if match:
            version = f"{match.group(1)}.{match.group(2)}"
            if match.group(1) != "4":
                logger.warning("godot.target_version %s is not a 4.x version", version)
            return version
        logger.warning("godot.target_version %r is not understood; ignoring it", godot.target_version)
    if godot.executable_path:
        try:
            proc = subprocess.run(
                [str(godot.executable_path), "--version"],
                capture_output=True, text=True, timeout=30, check=False,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            logger.warning("Could not run Godot to read its version: %s", exc)
            return None
        first_line = (proc.stdout or "").strip().splitlines()[:1]
        match = _VERSION_RE.search(first_line[0][:80]) if first_line else None
        if match:
            return f"{match.group(1)}.{match.group(2)}"
        logger.warning("Could not parse Godot version output: %r", (proc.stdout or "")[:80])
    return None


def render_project_godot(
    *,
    title: str,
    main_scene: str,
    autoloads: dict[str, str],
    input_actions: list[dict[str, Any]],
    width: int,
    height: int,
    clear_color: str,
    version: str | None,
    pixel_art: bool,
) -> str:
    """Build the text of project.godot (config_version=5, Godot 4)."""
    features = ([version] if version else []) + ["GL Compatibility"]
    lines = [
        "; Engine configuration file.",
        "; Generated by Godot Game Studio.",
        "",
        "config_version=5",
        "",
        "[application]",
        "",
        f'config/name="{_esc(title)}"',
        f'run/main_scene="res://{main_scene}"',
        "config/features=PackedStringArray(" + ", ".join(f'"{f}"' for f in features) + ")",
        'config/icon="res://icon.svg"',
        "",
    ]
    if autoloads:
        lines += ["[autoload]", ""]
        lines += [f'{name}="*res://{path}"' for name, path in autoloads.items()]
        lines.append("")
    lines += [
        "[display]",
        "",
        f"window/size/viewport_width={int(width)}",
        f"window/size/viewport_height={int(height)}",
        'window/stretch/mode="canvas_items"',
        'window/stretch/aspect="keep"',
        "",
        "[input]",
        "",
    ]
    for action in input_actions:
        keys = list(dict.fromkeys(action["keys"]))
        events = ", ".join(_event_for(k) for k in keys)
        lines += [f"{action['name']}={{", '"deadzone": 0.5,', f'"events": [{events}]', "}"]
    lines += ["", "[rendering]", "", 'renderer/rendering_method="gl_compatibility"']
    if pixel_art:
        lines.append("textures/canvas_textures/default_texture_filter=0")
    lines.append(f"environment/defaults/default_clear_color={_color(clear_color)}")
    return "\n".join(lines) + "\n"


def _icon_svg(background: str, foreground: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">'
        f'<rect width="128" height="128" rx="24" fill="{background}"/>'
        f'<circle cx="64" cy="64" r="34" fill="{foreground}"/></svg>\n'
    )


def write_project_files(ctx: ProjectContext, settings: dict[str, Any]) -> dict[str, Any]:
    """Write project.godot, icon.svg and .gitignore from the programmer's settings."""
    root = ctx.project_dir
    autoloads: dict[str, str] = settings.get("autoloads", {})
    referenced = [settings["main_scene"], *autoloads.values()]
    missing = [p for p in referenced if not resolve_inside(root, p).is_file()]
    if missing:
        raise ProjectWriteError(f"project.godot would reference missing files: {missing}")

    design = ctx.get_artifact("game_designer", {}) or {}
    art = ctx.get_artifact("art", {}) or {}
    sprites = art.get("sprites", [])
    palette = art.get("palette", [])
    clear_color = art.get("clear_color") or "#202030"
    player_color = next((c["hex"] for c in palette if c.get("role") == "player"), "#ffffff")
    pixel_art = bool(sprites) and sum(1 for s in sprites if s.get("style") == "pixel") > len(sprites) / 2

    warnings: list[str] = []
    version = detect_godot_version(ctx.config.godot)
    if version is None:
        warnings.append(
            "Godot version unknown: set godot.target_version in config.toml (or godot.executable_path) "
            "so project.godot declares the right engine version."
        )

    text = render_project_godot(
        title=str(design.get("title") or "Generated Game"),
        main_scene=settings["main_scene"],
        autoloads=autoloads,
        input_actions=settings["input_actions"],
        width=settings.get("window_width", 1152),
        height=settings.get("window_height", 648),
        clear_color=clear_color,
        version=version,
        pixel_art=pixel_art,
    )
    files = {
        "project.godot": text,
        "icon.svg": _icon_svg(clear_color, player_color),
        ".gitignore": ".godot/\n",
    }
    for rel, content in files.items():
        resolve_inside(root, rel).write_text(content, encoding="utf-8", newline="\n")
    return {"files": sorted(files), "godot_version": version, "warnings": warnings}
